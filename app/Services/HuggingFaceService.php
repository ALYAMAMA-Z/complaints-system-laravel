<?php

namespace App\Services;

class HuggingFaceService
{
    public function classifyText($text)
    {
        $lowerText = mb_strtolower($text);

        // تعريف الكلمات المفتاحية لكل فئة (الأكثر تخصصاً أولاً)
        $categories = [
            'إنارة' => ['إنارة', 'ضوء', 'عمود', 'ظلام', 'كهرباء', 'لمبة', 'عواميد', 'مظلم', 'معطلة', 'منارة'],
            'مياه' => ['مياه', 'صرف صحي', 'مجاري', 'تسرب', 'فيضان', 'غرق', 'بويب', 'بالوعة', 'أنبوب'],
            'طرقات' => ['حفرة', 'حفر', 'رصيف', 'جسر', 'تصدع', 'انهيار', 'مطبة', 'سرعة', 'شاخص', 'مطبات'],
            'نظافة' => ['نفايات', 'قمامة', 'وسخ', 'قاذورات', 'حاويات', 'كنس', 'زراقة', 'مزبلة'],
            'حدائق' => ['حديقة', 'منتزه', 'شجرة', 'عشب', 'مقعد', 'ملعب', 'متنزه'],
            'إزعاج' => ['إزعاج', 'ضوضاء', 'صوت', 'أصوات', 'مزعج', 'هدير', 'مكبرات'],
            'حيوانات' => ['كلب', 'قط', 'حيوان', 'ضال', 'شارد', 'كلاب', 'قطط'],
        ];

        // البحث عن الكلمات المفتاحية
        foreach ($categories as $category => $keywords) {
            foreach ($keywords as $keyword) {
                if (mb_strpos($lowerText, $keyword) !== false) {
                    return $category;
                }
            }
        }

        return 'أخرى';
    }
}
